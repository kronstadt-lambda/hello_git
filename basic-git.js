/*
 * Commands:
 * git checkout [file]: changes the file to the last commit.
 * git checkout [branch]: changes the branch.
 * git checkout -b [branch]: creates a new branch.
 * git reset: resets the repository to the last commit. Unstage all files.
 * git reset [file]: unstages the file.
 * git config --global alias.tree "log --graph --decorate --all --oneline": sets an alias for the command tree.
 * git tree: shows the log of the repository in a graph.
 */